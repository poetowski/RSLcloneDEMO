export const CELL_H = 9;
export const BASELINE = 6;

export interface FontJson {
  cellH: number;
  baseline: number;
  lineH: number;
  /** variant -> char -> [x, y, w] in the atlas (height is always cellH) */
  glyphs: Record<'regular' | 'bold', Record<string, [number, number, number]>>;
}

function glyphBitmap(rows: string[], bold: boolean): Bitmap {
  const w0 = Math.max(...rows.map((r) => r.length));
  const w = w0 + (bold ? 1 : 0);
  const b = new Bitmap(Math.max(1, w), CELL_H);
  const white = hex('#ffffff');
  rows.forEach((r, y) => {
    for (let x = 0; x < r.length; x++) {
      if (r[x] !== '#') continue;
      b.set(x, y, white);
      if (bold) b.set(x + 1, y, white);
    }
  });
  return b;
}

export function buildFont(out: string) {
  const chars = Object.keys(G);
  const atlas = new Bitmap(640, CELL_H * 2 + 2);
  const json: FontJson = { cellH: CELL_H, baseline: BASELINE, lineH: 11, glyphs: { regular: {}, bold: {} } };
  (['regular', 'bold'] as const).forEach((variant, vi) => {
    let x = 0;
    const y = vi * (CELL_H + 1);
    for (const ch of chars) {
      const bmp = glyphBitmap(G[ch], variant === 'bold');
      atlas.blit(bmp, x, y);
      json.glyphs[variant][ch] = [x, y, bmp.w];
      x += bmp.w + 1;
    }
  });
  atlas.save(path.join(out, 'ui', 'font.png'));
  writeJson(path.join(out, 'ui', 'font.json'), json);
  console.log(`  font: ${chars.length} glyphs x 2 variants`);
}
