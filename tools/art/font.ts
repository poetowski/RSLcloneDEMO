/** Blocks: a line "=X" names the glyph, the lines after it are its rows. */
function blocks(src: string): Record<string, string[]> {
  const o: Record<string, string[]> = {};
  let cur: string[] | null = null;
  for (const raw of src.split('\n')) {
    const line = raw.trim();
    if (line.length === 2 && line[0] === '=') o[line[1]] = cur = [];
    else if (cur && line) cur.push(line);
  }
  return o;
}

export type FaceId = 'regular' | 'bold' | 'display';

interface FaceSpec {
  glyphs: Record<string, string[]>;
  cap: number;
  cellH: number;
  /** pixels between glyphs */
  gap: number;
  /** width of a space */
  space: number;
  /** the runtime upper-cases text in this face */
  caps: boolean;
}

const FACES: Record<FaceId, FaceSpec> = {
  regular: { glyphs: REGULAR, cap: 7, cellH: 9, gap: 1, space: 3, caps: false },
  bold: { glyphs: BOLD, cap: 7, cellH: 9, gap: 1, space: 3, caps: false },
  display: { glyphs: DISPLAY, cap: 13, cellH: 18, gap: 2, space: 5, caps: true },
};

export const LINE_H = 11;

export interface FaceJson {
  /** top of this face's row in the atlas */
  y: number;
  cellH: number;
  cap: number;
  gap: number;
  caps: boolean;
  /** char -> [x, y, w] in the atlas (height is always cellH) */
  glyphs: Record<string, [number, number, number]>;
}

export interface FontJson {
  lineH: number;
  faces: Record<FaceId, FaceJson>;
}

export function buildFont(out: string) {
  const ids = Object.keys(FACES) as FaceId[];
  const width = (f: FaceSpec) => Object.values(f.glyphs).reduce((a, g) => a + Math.max(...g.map((r) => r.length)) + 1, f.space);
  const atlas = new Bitmap(Math.max(...ids.map((id) => width(FACES[id]))), ids.reduce((a, id) => a + FACES[id].cellH + 1, 0));
  const white = hex('#ffffff');
  const json: FontJson = { lineH: LINE_H, faces: {} as Record<FaceId, FaceJson> };
  let y = 0;
  for (const id of ids) {
    const f = FACES[id];
    const face: FaceJson = { y, cellH: f.cellH, cap: f.cap, gap: f.gap, caps: f.caps, glyphs: {} };
    let x = 0;
    for (const [ch, g] of Object.entries(f.glyphs)) {
      const w = Math.max(...g.map((r) => r.length));
      if (g.length > f.cellH) throw new Error(`font ${id} '${ch}' is taller than its cell`);
      g.forEach((r, yy) => [...r].forEach((p, xx) => p === '#' && atlas.set(x + xx, y + yy, white)));
      face.glyphs[ch] = [x, y, w];
      x += w + 1;
    }
    face.glyphs[' '] = [x, y, f.space];
    json.faces[id] = face;
    y += f.cellH + 1;
  }
  atlas.save(path.join(out, 'ui', 'font.png'));
  writeJson(path.join(out, 'ui', 'font.json'), json);
  console.log(`  font: ${ids.map((id) => `${id} ${Object.keys(FACES[id].glyphs).length}`).join(', ')} glyphs`);
}
