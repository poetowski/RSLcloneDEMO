/** Glyphs a face lacks are drawn as `?`; bold symbols nobody designed are the regular one, one pixel wider. */
function dilate(r: string[]): string[] {
  const w = Math.max(...r.map((x) => x.length)) + 1;
  return r.map((row) => [...Array(w)].map((_, x) => (row[x] === '#' || row[x - 1] === '#' ? '#' : '.')).join(''));
}
